async function deliver(sql,env,{mode='client',identifier='',clientId=null,title,body,url='/',createdBy='Administrador',source='manual'}){
  await ensureTables(sql);
  const templateTitle=text(title).slice(0,90),templateBody=text(body).slice(0,500),clickUrl=normalizeClickUrl(url);
  if(!templateTitle||!templateBody)throw Object.assign(new Error('Informe o título e a mensagem da notificação.'),{statusCode:400});
  let clients=[],targetClient=null;
  if(mode==='all')clients=await allAuthorizedClients(sql);
  else{
    targetClient=clientId?await clientById(sql,clientId):await resolveClient(sql,identifier);
    if(!targetClient)throw Object.assign(new Error('Cliente não encontrado pelo CPF/CNPJ ou contrato informado.'),{statusCode:404});
    clients=[targetClient];
  }
  if(!clients.length)throw Object.assign(new Error(mode==='all'?'Nenhum dispositivo autorizou notificações ainda.':'Cliente não encontrado.'),{statusCode:409});
  const state=await loadState(sql),vapid=await readVapid(env,sql);
  if(!vapid?.privateJWK)throw Object.assign(new Error('As chaves de notificação não estão disponíveis.'),{statusCode:503});
  const deliveryKey=`${source}:${crypto.randomUUID()}`,perClient=[];let sent=0,failed=0,total=0;
  for(const client of clients){
    const context=variableContext(state,client),renderedTitle=renderVariables(templateTitle,context).slice(0,90),renderedBody=renderVariables(templateBody,context).slice(0,500),subscriptions=await subscriptionsFor(sql,client.id),payload=notificationPayload(renderedTitle,renderedBody,clickUrl,`fibra-${crypto.randomUUID().replace(/-/g,'').slice(0,18)}`),result=subscriptions.length?await sendRows(sql,subscriptions,vapid,payload):{sent:0,failed:0,total:0};
    sent+=result.sent;failed+=result.failed;total+=result.total;perClient.push({client,renderedTitle,renderedBody,result});
  }
  if(mode==='client'&&total===0&&source==='manual')throw Object.assign(new Error('Este cliente ainda não autorizou notificações em nenhum dispositivo.'),{statusCode:409});
  const history=await sql`INSERT INTO pp_push_messages (target_client_id,target_mode,title,body,click_url,sent_count,failed_count,created_by_name) VALUES (${mode==='client'?Number(targetClient.id):null},${mode},${templateTitle},${templateBody},${clickUrl},${sent},${failed},${text(createdBy).slice(0,160)||'Administrador'}) RETURNING id,created_at`;
  const historyId=history?.[0]?.id,createdAt=history?.[0]?.created_at||new Date().toISOString();
  for(const item of perClient){const key=historyId?`message:${historyId}${mode==='all'?`:${item.client.id}`:''}`:`${deliveryKey}:${item.client.id}`;await recordInbox(sql,item.client.id,key,item.renderedTitle,item.renderedBody,clickUrl,createdAt)}
  return {sent,failed,total,clients:perClient.length,targetClient:targetClient?{id:Number(targetClient.id),name:text(targetClient.name),contract:text(targetClient.contract_number)}:null};
}

