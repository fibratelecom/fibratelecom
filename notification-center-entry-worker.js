async function processDueSchedules(env){
  if(!env?.DATABASE_URL)return {processed:0,sent:0,failed:0};
  const sql=neon(env.DATABASE_URL);await ensureTables(sql);
  const rows=await sql`UPDATE pp_notification_schedules SET status='sending' WHERE id IN (SELECT id FROM pp_notification_schedules WHERE status='pending' AND scheduled_for<=now() ORDER BY scheduled_for ASC LIMIT 20 FOR UPDATE SKIP LOCKED) RETURNING *`;
  let sent=0,failed=0;
  for(const row of rows||[]){
    try{
      const result=await deliver(sql,env,{mode:row.target_mode==='all'?'all':'client',clientId:row.target_client_id,title:row.title,body:row.body,url:row.click_url,createdBy:`Agendado · ${text(row.created_by_name)||'Administrador'}`,source:`schedule-${row.id}`});
      sent+=Number(result.sent)||0;failed+=Number(result.failed)||0;
      const noDevice=row.target_mode!=='all'&&Number(result.total)===0;
      await sql`UPDATE pp_notification_schedules SET status=${noDevice?'failed':'sent'},sent_count=${Number(result.sent)||0},failed_count=${Number(result.failed)||(noDevice?1:0)},sent_at=now(),last_error=${noDevice?'Cliente sem dispositivo autorizado no horário do envio.':null} WHERE id=${Number(row.id)}`;
    }catch(error){failed++;await sql`UPDATE pp_notification_schedules SET status='failed',failed_count=failed_count+1,last_error=${text(error instanceof Error?error.message:error).slice(0,500)},sent_at=now() WHERE id=${Number(row.id)}`}
  }
  await syncInboxFromMessages(env,sql);
  return {processed:rows?.length||0,sent,failed};
}

async function handleInbox(request,env,data,cors){
  if(!env.DATABASE_URL)throw Object.assign(new Error('Conexão com o Provedor Plus não configurada.'),{statusCode:503});
  const session=await verifySession(data?.session,env),sql=neon(env.DATABASE_URL);await ensureTables(sql);await syncInboxFromMessages(env,sql);
  const action=text(data?._action);
  if(action==='inbox'){
    const items=await sql`SELECT id,title,body,click_url,read_at,created_at FROM pp_notification_inbox WHERE client_id=${session.clientId} ORDER BY created_at DESC,id DESC LIMIT 50`,count=await sql`SELECT COUNT(*)::int AS unread FROM pp_notification_inbox WHERE client_id=${session.clientId} AND read_at IS NULL`;
    return json({ok:true,data:{items:(items||[]).map(row=>({id:Number(row.id),title:text(row.title),body:text(row.body),clickUrl:text(row.click_url),readAt:row.read_at,createdAt:row.created_at})),unread:Number(count?.[0]?.unread)||0}},200,cors);
  }
  if(action==='read'){
    const id=Number(data?.id)||0;if(!id)throw Object.assign(new Error('Notificação inválida.'),{statusCode:400});
    await sql`UPDATE pp_notification_inbox SET read_at=COALESCE(read_at,now()) WHERE id=${id} AND client_id=${session.clientId}`;
    const count=await sql`SELECT COUNT(*)::int AS unread FROM pp_notification_inbox WHERE client_id=${session.clientId} AND read_at IS NULL`;
    return json({ok:true,data:{unread:Number(count?.[0]?.unread)||0}},200,cors);
  }
  if(action==='read-all'){
    await sql`UPDATE pp_notification_inbox SET read_at=COALESCE(read_at,now()) WHERE client_id=${session.clientId} AND read_at IS NULL`;
    return json({ok:true,data:{unread:0}},200,cors);
  }
  throw Object.assign(new Error('Ação da caixa de notificações não permitida.'),{statusCode:400});
}

