async function loadState(sql){const rows=await sql`SELECT value FROM pp_settings WHERE key=${STATE_KEY} LIMIT 1`;return parseObject(rows?.[0]?.value)}
async function loadSettings(sql){const rows=await sql`SELECT value FROM pp_settings WHERE key=${OPS_SETTINGS_KEY} LIMIT 1`;return safeSettings(rows?.[0]?.value)}
async function saveSettings(sql,value){const next=safeSettings(value),raw=JSON.stringify(next),at=new Date().toISOString();await sql`INSERT INTO pp_settings (key,value,updated_at) VALUES (${OPS_SETTINGS_KEY},${raw}::jsonb,${at}) ON CONFLICT (key) DO UPDATE SET value=EXCLUDED.value,updated_at=EXCLUDED.updated_at`;return next}

async function pushCryptoKey(env){const secret=text(env.BANK_SECRET_KEY)||text(env.PORTAL_SESSION_SECRET)||text(env.DATABASE_URL);if(!secret)throw new Error('Chave de proteção das notificações não configurada.');const raw=await crypto.subtle.digest('SHA-256',enc.encode(`provedor-plus-push-v1|${secret}`));return crypto.subtle.importKey('raw',raw,{name:'AES-GCM'},false,['decrypt'])}
async function readVapid(env,sql){const rows=await sql`SELECT value FROM pp_settings WHERE key=${VAPID_KEY} LIMIT 1`,record=rows?.[0]?.value;if(!record?.iv||!record?.data)return null;const key=await pushCryptoKey(env),plain=await crypto.subtle.decrypt({name:'AES-GCM',iv:base64UrlBytes(record.iv)},key,base64UrlBytes(record.data));return JSON.parse(new TextDecoder().decode(plain))}

async function sendOne(sql,row,vapid,payload){
  try{
    const built=await buildPushHTTPRequest({privateJWK:vapid.privateJWK,subscription:{endpoint:row.endpoint,keys:{p256dh:row.p256dh,auth:row.auth}},message:{payload,adminContact:vapid.subject||'mailto:adrianomoreirausuarios@gmail.com',options:{ttl:86400,urgency:'normal',topic:text(payload.tag).replace(/[^A-Za-z0-9_-]/g,'').slice(0,32)||'fibra-plus'}}});
    const response=await fetch(built.endpoint,{method:'POST',headers:built.headers,body:built.body,redirect:'manual'}),now=new Date().toISOString();
    if(response.ok){await sql`UPDATE pp_push_subscriptions SET active=true,last_success_at=${now},last_error=NULL,updated_at=${now} WHERE id=${Number(row.id)}`;return {ok:true}}
    const error=`Push HTTP ${response.status}`;if(response.status===404||response.status===410)await sql`UPDATE pp_push_subscriptions SET active=false,last_error=${error},updated_at=${now} WHERE id=${Number(row.id)}`;else await sql`UPDATE pp_push_subscriptions SET last_error=${error},updated_at=${now} WHERE id=${Number(row.id)}`;return {ok:false,error};
  }catch(error){const message=error instanceof Error?error.message:String(error),now=new Date().toISOString();try{await sql`UPDATE pp_push_subscriptions SET last_error=${message.slice(0,500)},updated_at=${now} WHERE id=${Number(row.id)}`}catch{}return {ok:false,error:message}}
}
async function sendRows(sql,rows,vapid,payload){let sent=0,failed=0;for(let start=0;start<rows.length;start+=10){const results=await Promise.all(rows.slice(start,start+10).map(row=>sendOne(sql,row,vapid,payload)));for(const result of results)result.ok?sent++:failed++}return {sent,failed,total:rows.length}}

async function attemptEvent(sql,env,row){
  const claimed=await sql`UPDATE pp_push_events SET attempts=attempts+1,last_attempt_at=now() WHERE id=${Number(row.id)} AND completed=false AND (last_attempt_at IS NULL OR last_attempt_at<now()-interval '2 minutes') RETURNING *`;
  const event=claimed?.[0];if(!event)return {skipped:true};
  const subscriptions=await sql`SELECT id,client_id,endpoint,p256dh,auth FROM pp_push_subscriptions WHERE client_id=${Number(event.client_id)} AND active=true ORDER BY id ASC`;if(!subscriptions.length)return {skipped:true,reason:'no-subscriptions'};
  const vapid=await readVapid(env,sql);if(!vapid?.privateJWK)return {skipped:true,reason:'no-vapid'};
  const payload=notificationPayload(event.title,event.body,event.click_url,`ops-${text(event.event_key).replace(/[^A-Za-z0-9_-]/g,'-').slice(-38)}`),result=await sendRows(sql,subscriptions,vapid,payload),completed=result.sent>0,sentAt=completed?new Date().toISOString():null;
  await sql`UPDATE pp_push_events SET sent_count=sent_count+${result.sent},failed_count=failed_count+${result.failed},completed=${completed},sent_at=COALESCE(sent_at,${sentAt}) WHERE id=${Number(event.id)}`;
  if(completed)await sql`INSERT INTO pp_push_messages (target_client_id,target_mode,title,body,click_url,sent_count,failed_count,created_by_name) VALUES (${Number(event.client_id)},'client',${text(event.title)},${text(event.body)},${text(event.click_url)},${result.sent},${result.failed},${`Automático · ${text(event.event_type).replace(/^operational:/,'')}`})`;
  return result;
}

async function sendAutomaticEvent(sql,env,event){
  const clientId=Number(event?.clientId)||0,key=text(event?.key),type=`operational:${text(event?.type)||'aviso'}`,title=text(event?.title).slice(0,90),body=text(event?.body).slice(0,500),url=normalizeClickUrl(event?.url||'/');
  if(!clientId||!key||!title||!body)return {skipped:true};
  const subscriptions=await sql`SELECT id FROM pp_push_subscriptions WHERE client_id=${clientId} AND active=true LIMIT 1`;if(!subscriptions.length)return {skipped:true,reason:'no-subscriptions'};
  await sql`INSERT INTO pp_push_events (event_key,client_id,event_type,title,body,click_url) VALUES (${key},${clientId},${type},${title},${body},${url}) ON CONFLICT (event_key) DO NOTHING`;
  const rows=await sql`SELECT * FROM pp_push_events WHERE event_key=${key} LIMIT 1`;return rows?.[0]?attemptEvent(sql,env,rows[0]):{skipped:true};
}

function localClientMap(state){return new Map((Array.isArray(state?.clients)?state.clients:[]).map(item=>[Number(item?.id)||0,item]))}
function planNameFor(row,state){const direct=text(row?.plan);if(direct)return direct;const plan=(Array.isArray(state?.plans)?state.plans:[]).find(item=>Number(item?.id)===Number(row?.plan_id));return text(plan?.name)||'seu novo plano'}

async function statusAndPlanEvents(sql,state,settings){
  const rows=await sql`SELECT c.id,c.name,c.status,c.plan,c.plan_id,c.updated_at,o.client_id AS observer_id,o.last_status,o.last_plan FROM pp_clients c LEFT JOIN pp_push_observer_state o ON o.client_id=c.id ORDER BY c.id ASC`,locals=localClientMap(state),events=[];
  for(const row of rows||[]){
    if(!row.observer_id)continue;
    const clientId=Number(row.id),currentStatus=text(row.status),oldStatus=text(row.last_status),currentPlan=`${text(row.plan)}|${row.plan_id??''}`,oldPlan=text(row.last_plan),local=locals.get(clientId)||{},trustActive=recent(local?.trust_release_at,36)&&new Date(text(local?.trust_release_until)).getTime()>Date.now(),trustReblocked=recent(local?.trust_release_reblocked_at,36);
    if(normalize(currentStatus)!==normalize(oldStatus)){
      const wasBlocked=blockedStatus(oldStatus),isBlocked=blockedStatus(currentStatus),stamp=text(row.updated_at)||Date.now();
      if(!wasBlocked&&isBlocked&&settings.statusSuspended&&!trustReblocked)events.push({key:`status-blocked:${clientId}:${stamp}`,clientId,type:'internet suspensa',title:'Conexão suspensa',body:'Sua conexão foi suspensa. Consulte suas faturas e opções de regularização na Área do Cliente.',url:'/#conexao'});
      if(wasBlocked&&!isBlocked&&settings.statusRestored&&!trustActive)events.push({key:`status-restored:${clientId}:${stamp}`,clientId,type:'internet liberada',title:'Conexão liberada',body:'Seu acesso à internet foi liberado novamente.',url:'/#conexao'});
    }
    if(currentPlan!==oldPlan&&settings.planChange){const stamp=text(row.updated_at)||Date.now(),name=planNameFor(row,state);events.push({key:`plan-change:${clientId}:${stamp}`,clientId,type:'plano alterado',title:'Plano atualizado',body:`Seu plano foi atualizado para ${name}. Consulte os detalhes na Área do Cliente.`,url:'/#perfil'})}
  }
  await sql`INSERT INTO pp_push_observer_state (client_id,last_status,last_plan,updated_at) SELECT id,status,COALESCE(plan,'')||'|'||COALESCE(plan_id::text,''),now() FROM pp_clients ON CONFLICT (client_id) DO UPDATE SET last_status=EXCLUDED.last_status,last_plan=EXCLUDED.last_plan,updated_at=now()`;
  return events;
}

function trustEvents(state,settings){
  if(!settings.trustRelease)return [];
  const events=[];
  for(const client of Array.isArray(state?.clients)?state.clients:[]){
    const clientId=Number(client?.id)||0;if(!clientId)continue;
    if(recent(client?.trust_release_at,36)){const until=text(client?.trust_release_until),suffix=until?` até ${brDateTime(until)}`:'';events.push({key:`trust-start:${clientId}:${text(client.trust_release_at)}`,clientId,type:'liberação por confiança',title:'Liberação por confiança ativada',body:`Sua conexão foi liberada temporariamente por confiança${suffix}.`,url:'/#conexao'})}
    if(recent(client?.trust_release_reblocked_at,36))events.push({key:`trust-reblocked:${clientId}:${text(client.trust_release_reblocked_at)}`,clientId,type:'fim da liberação por confiança',title:'Liberação por confiança encerrada',body:'O período de liberação por confiança terminou e a conexão foi bloqueada novamente por pendência.',url:'/#conexao'});
    if(recent(client?.trust_release_completed_at,36)&&text(client?.trust_release_completion_reason)==='payment')events.push({key:`trust-paid:${clientId}:${text(client.trust_release_completed_at)}`,clientId,type:'liberação por confiança concluída',title:'Conexão mantida liberada',body:'A pendência foi regularizada. Sua conexão permanece liberada normalmente.',url:'/#conexao'});
  }
  return events;
}

async function dueChangeEvents(sql,settings){
  if(!settings.dueChange)return [];
  try{
    const rows=await sql`SELECT id,protocol,client_id,status,details,created_at,closed_at FROM pp_protocols WHERE client_id IS NOT NULL AND category='Vencimento' AND subject='Alteração de vencimento' AND status='Concluído' AND created_at>=now()-interval '36 hours' ORDER BY id DESC LIMIT 100`,events=[];
    for(const row of rows||[]){const details=parseObject(row.details),oldDay=Number(details.oldDay)||0,newDay=Number(details.newDay)||0,clientId=Number(row.client_id)||0;if(!clientId)continue;events.push({key:`due-change:${row.id}:${text(row.closed_at||row.created_at)}`,clientId,type:'mudança de vencimento',title:'Vencimento alterado',body:newDay?`Seu vencimento foi alterado${oldDay?` do dia ${oldDay}`:''} para o dia ${newDay}. Protocolo ${text(row.protocol)}.`:`Sua alteração de vencimento foi concluída. Protocolo ${text(row.protocol)}.`,url:'/#perfil'})}
    return events;
  }catch{return []}
}

function negotiationEvents(state,settings){
  if(!settings.negotiation)return [];
  const agreements=Array.isArray(state?.negotiations)?state.negotiations:[],invoices=Array.isArray(state?.invoices)?state.invoices:[],events=[];
  for(const agreement of agreements){
    const id=text(agreement?.id),clientId=Number(agreement?.client_id)||0;if(!id||!clientId)continue;
    const created=text(agreement?.confirmed_at||agreement?.created_at),status=normalize(agreement?.status),parts=Math.max(1,Math.round(Number(agreement?.installment_total)||1)),total=Math.max(0,Math.round(Number(agreement?.negotiated_amount_cents)||0)),entry=Math.max(0,Math.round(Number(agreement?.entry_cents)||0));
    if((status.includes('ativo')||status.includes('concluido'))&&recent(created,36)){let body=`Seu acordo ${id} foi confirmado em ${parts} parcela${parts===1?'':'s'}`;if(total)body+=` no total de ${brl(total)}`;if(entry&&parts>1)body+=`, com entrada de ${brl(entry)}`;body+='.';events.push({key:`negotiation-created:${id}`,clientId,type:'negociação criada',title:'Negociação confirmada',body,url:'/#faturas'})}
    const wanted=new Set((Array.isArray(agreement?.new_invoice_ids)?agreement.new_invoice_ids:[]).map(String)),related=invoices.filter(invoice=>wanted.size?wanted.has(String(invoice?.id)):text(invoice?.negotiation_id)===id&&!normalize(invoice?.status).includes('renegociado'));
    if(related.length&&related.every(invoice=>paidStatus(invoice?.status))){const paidTimes=related.map(invoice=>new Date(text(invoice?.paid_at)).getTime()).filter(Number.isFinite),lastPaid=paidTimes.length?new Date(Math.max(...paidTimes)).toISOString():'';if(recent(lastPaid,36))events.push({key:`negotiation-completed:${id}:${lastPaid}`,clientId,type:'acordo quitado',title:'Acordo concluído',body:`Seu acordo ${id} foi quitado. Todas as ${parts} parcela${parts===1?'':'s'} estão pagas.`,url:'/#faturas'})}
  }
  return events;
}

async function protocolEvents(sql,settings){
  if(!settings.protocols)return [];
  try{
    const rows=await sql`SELECT p.id,p.protocol,p.client_id,p.category,p.subject,p.status,p.created_at,p.closed_at,o.protocol_id AS observer_id,o.last_status FROM pp_protocols p LEFT JOIN pp_push_protocol_observer o ON o.protocol_id=p.id WHERE p.client_id IS NOT NULL AND (p.category ILIKE '%Atendimento%' OR p.category ILIKE '%Suporte%' OR p.category ILIKE '%Chamado%') ORDER BY p.id DESC LIMIT 300`,events=[];
    for(const row of rows||[]){const current=text(row.status),changed=Boolean(row.observer_id)&&normalize(current)!==normalize(row.last_status),isNew=!row.observer_id&&recent(row.created_at,36);if(!changed&&!isNew)continue;const status=normalize(current),done=status.includes('conclu')||status.includes('fech'),opened=status.includes('aberto'),title=done?'Protocolo concluído':opened?'Protocolo aberto':'Protocolo atualizado',body=`${text(row.protocol)||`Protocolo ${row.id}`} · ${text(row.subject)||text(row.category)} · Status: ${current||'Atualizado'}.`;events.push({key:`protocol:${row.id}:${status}:${text(row.closed_at||row.created_at)}`,clientId:Number(row.client_id),type:done?'protocolo concluído':opened?'protocolo aberto':'protocolo atualizado',title,body,url:'/'})}
    await sql`INSERT INTO pp_push_protocol_observer (protocol_id,last_status,updated_at) SELECT id,status,now() FROM pp_protocols WHERE client_id IS NOT NULL AND (category ILIKE '%Atendimento%' OR category ILIKE '%Suporte%' OR category ILIKE '%Chamado%') ON CONFLICT (protocol_id) DO UPDATE SET last_status=EXCLUDED.last_status,updated_at=now()`;
    return events;
  }catch{return []}
}

async function retryPending(sql,env){
  const rows=await sql`SELECT * FROM pp_push_events WHERE completed=false AND event_type LIKE 'operational:%' AND created_at>=now()-interval '7 days' AND (last_attempt_at IS NULL OR last_attempt_at<now()-interval '2 minutes') ORDER BY id ASC LIMIT 40`;let sent=0,failed=0;
  for(const row of rows||[]){try{const result=await attemptEvent(sql,env,row);sent+=Number(result?.sent)||0;failed+=Number(result?.failed)||0}catch{failed++}}
  return {sent,failed};
}

async function scanOperationalEvents(env){
  if(!env?.DATABASE_URL)return {scanned:false};
  const sql=neon(env.DATABASE_URL);await ensureTables(sql);const state=await loadState(sql),settings=await loadSettings(sql),events=[];
  events.push(...await statusAndPlanEvents(sql,state,settings));
  events.push(...trustEvents(state,settings));
  events.push(...await dueChangeEvents(sql,settings));
  events.push(...negotiationEvents(state,settings));
  events.push(...await protocolEvents(sql,settings));
  const unique=[...new Map(events.filter(item=>item?.clientId&&item?.key).map(item=>[item.key,item])).values()].slice(0,250);let sent=0,failed=0,skipped=0;
  for(const event of unique){try{const result=await sendAutomaticEvent(sql,env,event);if(result?.skipped)skipped++;else{sent+=Number(result?.sent)||0;failed+=Number(result?.failed)||0}}catch(error){failed++;console.error('Provedor Plus: falha em notificação operacional.',event?.type,error)}}
  const retry=await retryPending(sql,env);return {scanned:true,events:unique.length,sent:sent+retry.sent,failed:failed+retry.failed,skipped};
}

async function verifyPanelAdmin(request,env,ctx){
  const url=new URL(request.url),headers=new Headers(request.headers);headers.set('Content-Type','application/json');const probe=new Request(`${url.origin}/api/push-admin`,{method:'POST',headers,body:JSON.stringify({action:'stats'})}),response=await baseWorker.fetch(probe,env,ctx);if(!response.ok)throw Object.assign(new Error(response.status===403?'Somente o administrador pode alterar notificações automáticas.':'Sessão expirada ou não autenticada.'),{statusCode:response.status});return true;
}

async function handleOperations(request,env,ctx){
  if(request.method!=='POST')return json({ok:false,error:'Método não permitido.'},405);
  try{
    await verifyPanelAdmin(request,env,ctx);if(!env.DATABASE_URL)throw Object.assign(new Error('Conexão com o Neon não configurada.'),{statusCode:503});let body={};try{body=await request.json()}catch{}const action=text(body?.action),data=body?.data||{},sql=neon(env.DATABASE_URL);await ensureTables(sql);
    if(action==='get')return json({ok:true,data:{settings:await loadSettings(sql),financialAutomatic:['Fatura gerada','Vence amanhã','Fatura vencida','Pagamento confirmado','Cashback recebido']}});
    if(action==='save'){const current=await loadSettings(sql),next={...current};for(const key of Object.keys(DEFAULT_SETTINGS))if(data?.settings&&Object.prototype.hasOwnProperty.call(data.settings,key))next[key]=Boolean(data.settings[key]);return json({ok:true,data:{settings:await saveSettings(sql,next)}})}
    if(action==='scan-now')return json({ok:true,data:await scanOperationalEvents(env)});
    throw Object.assign(new Error('Ação de notificações operacionais não permitida.'),{statusCode:400});
  }catch(error){return json({ok:false,error:error instanceof Error?error.message:String(error)},Number(error?.statusCode)||500)}
}

async function shouldScanAfterRequest(request){
  if(request.method!=='POST')return false;
  const path=new URL(request.url).pathname;
  if(['/api/cloud-state','/api/bank-proxy','/api/customer-due-date','/api/customer-trust-release','/api/protocols'].includes(path))return true;
  if(path!=='/api/customer-portal')return false;
  let action='';try{const body=await request.clone().json();action=text(body?.action).toLowerCase()}catch{}
  return !['login','refresh','connection-test','negotiation-options','negotiation-preview','cashback-statement'].includes(action);
}

export default {
  async fetch(request,env,ctx){const path=new URL(request.url).pathname;if(path===OPS_PATH)return handleOperations(request,env,ctx);const scan=env?.DATABASE_URL?await shouldScanAfterRequest(request):false,response=await baseWorker.fetch(request,env,ctx);if(scan&&response?.ok){const task=scanOperationalEvents(env).catch(error=>console.error('Provedor Plus: falha ao verificar notificações operacionais.',error));if(typeof ctx?.waitUntil==='function')ctx.waitUntil(task)}return response},
  scheduled(controller,env,ctx){const result=baseWorker.scheduled(controller,env,ctx);if(env?.DATABASE_URL&&typeof ctx?.waitUntil==='function')ctx.waitUntil(scanOperationalEvents(env).catch(error=>console.error('Provedor Plus: falha no ciclo de notificações operacionais.',error)));return result}
};
