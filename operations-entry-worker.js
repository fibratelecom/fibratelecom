function json(data,status=200){return new Response(JSON.stringify(data),{status,headers:{'Content-Type':'application/json; charset=utf-8','Cache-Control':'no-store, max-age=0'}})}
function parseObject(value){if(value&&typeof value==='object'&&!Array.isArray(value))return value;if(typeof value==='string')try{const parsed=JSON.parse(value);return parsed&&typeof parsed==='object'&&!Array.isArray(parsed)?parsed:{}}catch{}return {}}
function base64UrlBytes(value){const raw=text(value).replace(/-/g,'+').replace(/_/g,'/'),padded=raw+'='.repeat((4-raw.length%4)%4),bin=atob(padded),out=new Uint8Array(bin.length);for(let i=0;i<bin.length;i++)out[i]=bin.charCodeAt(i);return out}
function recent(value,hours=36){const time=new Date(value).getTime();return Number.isFinite(time)&&Date.now()-time>=0&&Date.now()-time<=hours*3600000}
function brl(cents){return new Intl.NumberFormat('pt-BR',{style:'currency',currency:'BRL'}).format((Number(cents)||0)/100)}
function brDateTime(value){const d=new Date(value);return Number.isNaN(d.getTime())?'':new Intl.DateTimeFormat('pt-BR',{dateStyle:'short',timeStyle:'short',timeZone:'America/Sao_Paulo'}).format(d)}
function paidStatus(value){const status=normalize(value);return ['pago','paga','paid','baixado','recebido','recebida','quitado','quitada'].some(item=>status.includes(item))}
function blockedStatus(value){const status=normalize(value);return status.includes('bloqueado')||status.includes('suspenso')}
function safeSettings(value){const source=parseObject(value),next={};for(const key of Object.keys(DEFAULT_SETTINGS))next[key]=source[key]===undefined?DEFAULT_SETTINGS[key]:source[key]===true||String(source[key]).toLowerCase()==='true';return next}
function normalizeClickUrl(value='/'){const raw=text(value);return raw.startsWith('/')?`${CLIENT_APP_ORIGIN}${raw}`:`${CLIENT_APP_ORIGIN}/`}
function notificationPayload(title,body,url,tag){return {title:text(title)||'Fibra+',body:text(body),icon:`${CLIENT_APP_ORIGIN}/icons/fibra-app-192.png?v=15`,badge:`${CLIENT_APP_ORIGIN}/icons/fibra-app-192.png?v=15`,tag:text(tag)||'fibra-plus',lang:'pt-BR',data:{url:normalizeClickUrl(url)}}}

